import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { InstallmentImportDialog } from './InstallmentImportDialog';
import { useEMIWorkbookStore } from '../../../store/emiWorkbookStore';
import { useInterEntityTransfersStore } from '../../../store/interEntityTransfersStore';
import { usePlannedCashWorkbookStore } from '../../../store/plannedCashWorkbookStore';
import type { EMILoan } from '../../../types/emiWorkbook';
vi.mock('../../../lib/firebase/client', () => ({ auth: { currentUser: { uid: 'fixture' } }, db: null, firebaseReady: false }));
vi.mock('../../../lib/firebase/useEnsureSignedIn', () => ({ useEnsureSignedIn: () => async () => true }));
vi.mock('../../../components/ConfirmDialog', () => ({ confirmDialog: async () => true }));
const original = useEMIWorkbookStore.getState().workbook, links = useInterEntityTransfersStore.getState().workbook, plans = usePlannedCashWorkbookStore.getState().workbook;
afterEach(() => { cleanup(); useEMIWorkbookStore.getState().setWorkbook(original); useInterEntityTransfersStore.getState().setWorkbook(links); usePlannedCashWorkbookStore.getState().setWorkbook(plans); });
it('requires preview, review acknowledgement and typed confirmation before replacing a fixture ledger', async () => {
  const loan: EMILoan = { id: 'fixture-import', name: 'Property', lender: 'Seller', principal: 1000, totalToReturn: 1000, tenureMonths: 10, startDate: '2024-01-01', currencyCode: 'PKR', repaymentMode: 'fixedTotal' };
  useEMIWorkbookStore.getState().setWorkbook({ settings: { defaultCurrency: 'PKR' }, entries: [loan], repayments: [{ id: 'old', loanId: loan.id, month: 1, date: '2024-02-01', amount: 100 }] });
  useInterEntityTransfersStore.getState().setWorkbook({ settings: {}, entries: [] });
  usePlannedCashWorkbookStore.getState().setWorkbook({ ...plans, budgetAllocations: [] });
  const onClose = vi.fn();
  render(<InstallmentImportDialog loan={loan} onClose={onClose} />);
  const file = new File(['fixture'], 'fixture.csv', { type: 'text/csv' });
  Object.defineProperty(file, 'text', { value: async () => 'Payment Desc,Due Month,Scheduled Amount,Payment Date,Paid Installment\nBooking,2024-03-23,200,2024-03-23,200\nRegular,2024-04-10,800,2024-06-04,350' });
  fireEvent.change(screen.getByLabelText('Installment workbook or CSV'), { target: { files: [file] } });
  fireEvent.click(await screen.findByRole('button', { name: 'Generate reconciliation preview' }));
  const apply = screen.getByRole('button', { name: 'Apply reviewed reconciliation' });
  expect((apply as HTMLButtonElement).disabled).toBe(true);
  expect(useEMIWorkbookStore.getState().workbook.repayments[0].id).toBe('old');
  fireEvent.click(screen.getByRole('checkbox', { name: /I reviewed/ }));
  fireEvent.change(screen.getByLabelText('Type Property to confirm replacement'), { target: { value: 'Property' } });
  expect((apply as HTMLButtonElement).disabled).toBe(false);
  fireEvent.click(apply);
  await waitFor(() => expect(onClose).toHaveBeenCalledOnce());
  const wb = useEMIWorkbookStore.getState().workbook;
  expect(wb.repayments.map(row => row.amount)).toEqual([200, 350]);
  expect(wb.reconciliationHistory?.[0].repayments[0]).toMatchObject({ id: 'old', amount: 100 });
});
